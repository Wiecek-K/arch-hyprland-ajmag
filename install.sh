#!/bin/bash

# Colors
GREEN='\033[0;32m'
BLUE='\033[0;34m'
NC='\033[0m'

echo -e "${BLUE}=== STARTING AJMAG HYPRLAND INSTALLATION ===${NC}"

# 1. Install YAY
if ! command -v yay &> /dev/null; then
    echo -e "${BLUE}Installing yay...${NC}"
    sudo pacman -S --needed git base-devel
    git clone https://aur.archlinux.org/yay.git
    cd yay
    makepkg -si
    cd ..
    rm -rf yay
fi

# 2. Install the suggested packages (packages.txt: what the config needs; no drivers, no applications)
echo -e "${BLUE}Installing packages...${NC}"
awk '!/^#/ && NF && !/AUR|optional/ {print $1}' packages.txt | sudo pacman -S --needed -
awk '!/^#/ && /AUR/ && !/optional/ {print $1}' packages.txt | yay -S --needed -

# 3. Enable Services
echo -e "${BLUE}Enabling system services...${NC}"
sudo systemctl enable --now bluetooth

# 5. Wallpapers (Optional Download)
echo -e "${BLUE}--- WALLPAPERS ---${NC}"
read -p "Do you want to download the wallpaper pack? (y/N): " download_wallpapers

if [[ "$download_wallpapers" =~ ^[Yy]$ ]]; then
    echo -e "${BLUE}Downloading wallpapers...${NC}"
    mkdir -p ~/Pictures/wallpapers
    
    # Clone only the images, depth 1 for speed
    # REPLACE THE URL BELOW WITH YOUR ACTUAL WALLPAPER REPO URL LATER
    git clone --depth 1 https://github.com/YOUR_USERNAME/ajmag-wallpapers.git ~/Pictures/wallpapers_temp
    
    # Move files and cleanup git folder
    cp -r ~/Pictures/wallpapers_temp/* ~/Pictures/wallpapers/
    rm -rf ~/Pictures/wallpapers_temp
    
    echo "Wallpapers installed."
    
    # Set initial wallpaper symlink
    FIRST_WALL=$(ls ~/Pictures/wallpapers/* | head -n 1)
    if [ -n "$FIRST_WALL" ]; then
        ln -sf "$FIRST_WALL" "$HOME/.config/hypr/current_wallpaper"
    fi
else
    echo "Skipping wallpapers. You will need to set a wallpaper manually using Super+W after adding your own images."
fi

# 6. Dotfiles
echo -e "${BLUE}Installing dotfiles...${NC}"
CONFIG_DIR="$HOME/.config"
REPO_CONFIG_DIR="$(pwd)/.config"

install_config() {
    local folder=$1
    if [ -d "$REPO_CONFIG_DIR/$folder" ]; then
        if [ -d "$CONFIG_DIR/$folder" ]; then
            mv "$CONFIG_DIR/$folder" "$CONFIG_DIR/${folder}_backup_$(date +%s)"
        fi
        cp -r "$REPO_CONFIG_DIR/$folder" "$CONFIG_DIR/"
    fi
}

folders=("hypr" "kitty" "matugen" "spicetify" "quickshell")
for folder in "${folders[@]}"; do
    install_config "$folder"
done

# Ajmashell (quickshell/ajmashell, AGPL-3.0-or-later): matugen writes its colours here and the shell watches this
# directory from the start, so it must exist before the first wallpaper is set.
mkdir -p "$HOME/.local/state/ajmashell" "$HOME/.local/share/applications"
cp .local/share/applications/ajmashell-keybinds.desktop "$HOME/.local/share/applications/"

# Screenshot folder: satty's Save (SUPER+CTRL+S, hypr/scripts/screenshot.sh) fails when it is missing. screenshot.sh also
# creates it on every screenshot; same path rule as there (xdg-user-dir, else ~/Pictures).
PICTURES_DIR=$(xdg-user-dir PICTURES 2>/dev/null)
if [ -z "$PICTURES_DIR" ] || [ "${PICTURES_DIR%/}" = "$HOME" ]; then
    PICTURES_DIR="$HOME/Pictures"
fi
mkdir -p "$PICTURES_DIR/Screenshots"

# Ajmashell runs as a systemd user service (started by hypr/configs/autostart.lua, restarted on failure);
# nm-applet and blueman-applet stay out of the session: the Bar's Orbita does their job.
mkdir -p "$CONFIG_DIR/systemd/user" "$CONFIG_DIR/autostart"
cp "$REPO_CONFIG_DIR/systemd/user/ajmashell.service" "$CONFIG_DIR/systemd/user/"
cp "$REPO_CONFIG_DIR/autostart/nm-applet.desktop" "$REPO_CONFIG_DIR/autostart/blueman.desktop" "$CONFIG_DIR/autostart/"
systemctl --user daemon-reload

# ZSH
if [ -f "$HOME/.zshrc" ]; then
    mv "$HOME/.zshrc" "$HOME/.zshrc_backup_$(date +%s)"
fi
cp "home_files/.zshrc" "$HOME/.zshrc"

# 6.5. Cursor Themes
echo -e "${BLUE}Installing cursor themes...${NC}"
mkdir -p "$HOME/.local/share/icons"
cp -r "local/share/icons/Vimix-hyprcursor" "$HOME/.local/share/icons/"
cp -r "local/share/icons/Vimix-cursors"    "$HOME/.local/share/icons/"
gsettings set org.gnome.desktop.interface cursor-theme 'Vimix-cursors'
gsettings set org.gnome.desktop.interface cursor-size 24
# Nautilus: "Open in Terminal" in the right-click menu opens kitty (nautilus-open-any-terminal, AUR)
gsettings set com.github.stunkymonkey.nautilus-open-any-terminal terminal kitty 2>/dev/null || true

# 7. Permissions & Fixes
chmod +x $HOME/.config/hypr/scripts/*.sh

# Monitor Failsafe (hyprland.lua loads monitors.lua via pcall — a missing file falls back to "preferred, auto")
if [ ! -f "$HOME/.config/hypr/monitors.lua" ]; then
    echo "-- Generated by install.sh — run nwg-displays to configure monitors" > "$HOME/.config/hypr/monitors.lua"
fi

# Validate Hyprland Lua config
Hyprland --verify-config -c "$HOME/.config/hypr/hyprland.lua" | sed -n '/Config parsing result/,$p'

# Set initial wallpaper symlink (to avoid errors)
FIRST_WALL=$(ls ~/Pictures/wallpapers/* | head -n 1)
if [ -n "$FIRST_WALL" ]; then
    ln -sf "$FIRST_WALL" "$HOME/.config/hypr/current_wallpaper"
fi

# 8. Zen Browser
echo -e "${BLUE}Configuring Zen Browser...${NC}"
ZEN_PROFILE=$(find "$HOME/.zen" -maxdepth 1 -type d -name "*.Default (release)" | head -n 1)
if [ -n "$ZEN_PROFILE" ]; then
    mkdir -p "$ZEN_PROFILE/chrome"
    cp "home_files/zen/chrome/userChrome.css" "$ZEN_PROFILE/chrome/userChrome.css"
    # matugen writes Zen's colours to ~/.local/state/ajmashell/zen-chrome/ ([templates.zen]): a link to the profile's chrome
    rm -rf "$HOME/.local/state/ajmashell/zen-chrome"
    ln -s "$ZEN_PROFILE/chrome" "$HOME/.local/state/ajmashell/zen-chrome"
fi
# Live colours after a wallpaper change, without a Zen restart (config.js header: how it works, roll back)
if [ -d /opt/zen-browser-bin ]; then
    sudo install -m 644 system/zen/config.js /opt/zen-browser-bin/config.js
    sudo install -m 644 system/zen/autoconfig.js /opt/zen-browser-bin/defaults/pref/autoconfig.js
fi

echo -e "${GREEN}=== INSTALLATION COMPLETE ===${NC}"
echo "Please restart your computer. Use Super+W to set theme."
